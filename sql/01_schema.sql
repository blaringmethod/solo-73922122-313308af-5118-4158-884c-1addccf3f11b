-- ============================================================================
-- 电表累计读数 -> 区间用电量  数据模型
-- PostgreSQL 13+
--
-- 区间语义: 同一只电表按 UTC 时刻排序, 相邻两条读数 (a, b) 形成
--           左开右闭区间 (a.read_at, b.read_at]
--   - 首条读数之前不存在区间
--   - b.replaced = true (换表后的首条读数): 区间电量缺测 energy_wh = NULL
--   - 否则 energy_wh = b.reading - a.reading, 若为负则加 1_000_000
--     (0..999999 整数 Wh 的单次回绕; 结果不可能再为负)
-- 区间行由数据库函数在写入路径上做持久化的增量维护, 不重扫整只电表。
-- ============================================================================

CREATE TABLE IF NOT EXISTS meters (
    meter_no  TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- 累计读数
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meter_readings (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_no  TEXT NOT NULL
              REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    read_at   TIMESTAMPTZ NOT NULL,        -- UTC 时刻
    reading   INTEGER NOT NULL CHECK (reading BETWEEN 0 AND 999999), -- Wh
    replaced  BOOLEAN NOT NULL DEFAULT false, -- 换表标记: 该读数为新表首读
    CONSTRAINT meter_readings_uk_meter_time UNIQUE (meter_no, read_at)
);

COMMENT ON TABLE meter_readings IS '电表累计读数; 同表同刻唯一';
COMMENT ON COLUMN meter_readings.replaced IS '换表标记=true 时, 以该读数为右端点的区间电量缺测';

-- 按电表取前驱/后继用 (唯一约束本身已是 (meter_no, read_at) 的 B-tree)

-- ---------------------------------------------------------------------------
-- 区间用电量 (左开右闭), 每个非首条读数对应一行
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reading_intervals (
    meter_no     TEXT NOT NULL
                 REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE CASCADE,
    start_read_at TIMESTAMPTZ NOT NULL,    -- 开区间端点 (前驱读数时刻)
    end_read_at   TIMESTAMPTZ NOT NULL,    -- 闭区间端点 (当前读数时刻)
    start_reading INTEGER,                 -- 前驱累计读数 (审计/溯源用)
    end_reading   INTEGER NOT NULL,        -- 右端读数
    energy_wh     INTEGER,                 -- 区间电量; NULL = 缺测(换表)
    CONSTRAINT reading_intervals_pk PRIMARY KEY (meter_no, end_read_at),
    CONSTRAINT reading_intervals_uk_start UNIQUE (meter_no, start_read_at),
    CONSTRAINT reading_intervals_chk_order CHECK (start_read_at < end_read_at),
    CONSTRAINT reading_intervals_chk_energy
        CHECK (energy_wh IS NULL OR energy_wh BETWEEN 0 AND 999999)
);

COMMENT ON TABLE reading_intervals IS '左开右闭区间 (start_read_at, end_read_at] 的电量; energy_wh 为 NULL 表示缺测';

-- 供数按电表 + 时间范围过滤
CREATE INDEX IF NOT EXISTS reading_intervals_idx_meter_end
    ON reading_intervals (meter_no, end_read_at);

-- ---------------------------------------------------------------------------
-- 换表工单: 按电表号 + UTC 换表时刻登记拆除读数(旧表末读)与装机读数(新表首读)
-- 同表同刻再次提交即更正 (UPSERT, 唯一约束保证)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS meter_work_orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_no         TEXT NOT NULL
                     REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE RESTRICT,
    replaced_at      TIMESTAMPTZ NOT NULL,          -- UTC 换表时刻
    removal_reading  INTEGER NOT NULL CHECK (removal_reading BETWEEN 0 AND 999999),
    install_reading  INTEGER NOT NULL CHECK (install_reading BETWEEN 0 AND 999999),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT meter_work_orders_uk UNIQUE (meter_no, replaced_at)
);

COMMENT ON TABLE meter_work_orders IS '换表工单; 同表同换表时刻唯一, 重复提交为更正';
COMMENT ON COLUMN meter_work_orders.removal_reading IS '拆除读数: 旧表最后累计读数 (0..999999 Wh)';
COMMENT ON COLUMN meter_work_orders.install_reading IS '装机读数: 新表首个累计读数 (0..999999 Wh)';

CREATE INDEX IF NOT EXISTS meter_work_orders_idx_meter_time
    ON meter_work_orders (meter_no, replaced_at);

-- ---------------------------------------------------------------------------
-- 补算子段 (持久化): 对一条换表缺测区间 (gap, energy_wh IS NULL),
-- 用换表时刻严格落在该缺测段两端之间的工单逐次切开得到的子段。
--   * 拆除读数结束上一段, 装机读数开启下一段; 最外两端沿用原采样读数;
--   * 每段沿用单次回绕 (interval_energy, replaced=false);
--   * 端点来自原采样读数时对应 work_order_at 为 NULL。
-- 外键 ON DELETE CASCADE: 源缺测段/工单被删或被替换时, 旧补算在同一事务撤下。
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS backfill_segments (
    meter_no              TEXT NOT NULL
                          REFERENCES meters(meter_no) ON UPDATE CASCADE ON DELETE CASCADE,
    gap_end_read_at       TIMESTAMPTZ NOT NULL,   -- 所属缺测段右端 (读数时刻)
    segment_index         INTEGER NOT NULL CHECK (segment_index >= 0),
    start_read_at         TIMESTAMPTZ NOT NULL,
    end_read_at           TIMESTAMPTZ NOT NULL,
    start_reading         INTEGER NOT NULL CHECK (start_reading BETWEEN 0 AND 999999),
    end_reading           INTEGER NOT NULL CHECK (end_reading BETWEEN 0 AND 999999),
    energy_wh             INTEGER NOT NULL CHECK (energy_wh BETWEEN 0 AND 999999),
    start_work_order_at   TIMESTAMPTZ,            -- NULL => 端点取自原采样读数
    end_work_order_at     TIMESTAMPTZ,            -- NULL => 端点取自原采样读数
    CONSTRAINT backfill_segments_pk
        PRIMARY KEY (meter_no, gap_end_read_at, segment_index),
    CONSTRAINT backfill_segments_chk_order CHECK (start_read_at < end_read_at),
    CONSTRAINT backfill_segments_fk_gap
        FOREIGN KEY (meter_no, gap_end_read_at)
        REFERENCES reading_intervals (meter_no, end_read_at)
        ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT backfill_segments_fk_start_wo
        FOREIGN KEY (meter_no, start_work_order_at)
        REFERENCES meter_work_orders (meter_no, replaced_at)
        ON UPDATE CASCADE ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT backfill_segments_fk_end_wo
        FOREIGN KEY (meter_no, end_work_order_at)
        REFERENCES meter_work_orders (meter_no, replaced_at)
        ON UPDATE CASCADE ON DELETE CASCADE
        DEFERRABLE INITIALLY DEFERRED
);

COMMENT ON TABLE backfill_segments IS '换表缺测段的持久化补算子段; 无源工单适用时不产生行 (缺测保留)';
COMMENT ON COLUMN backfill_segments.gap_end_read_at IS '本补算所属缺测区间 (reading_intervals) 的右端时刻';
COMMENT ON COLUMN backfill_segments.start_work_order_at IS '子段左端工单时刻; NULL 表示左端是原采样读数';
COMMENT ON COLUMN backfill_segments.end_work_order_at IS '子段右端工单时刻; NULL 表示右端是原采样读数';

CREATE INDEX IF NOT EXISTS backfill_segments_idx_meter_gap
    ON backfill_segments (meter_no, gap_end_read_at);

-- ============================================================================
-- 区间电量纯函数: 负差值按 1_000_000 单次回绕; 换表 => NULL(缺测)
-- ============================================================================
CREATE OR REPLACE FUNCTION interval_energy(
    p_prev_reading INTEGER,
    p_curr_reading INTEGER,
    p_curr_replaced BOOLEAN
) RETURNS INTEGER
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN p_curr_replaced THEN NULL
        WHEN p_curr_reading >= p_prev_reading THEN p_curr_reading - p_prev_reading
        ELSE p_curr_reading - p_prev_reading + 1000000
    END;
$$;
